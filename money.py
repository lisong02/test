# 个人记账工具
def my_money():
    bills = [
        {"事项":"工资","金额":8000,"类型":"收入"},
        {"事项":"吃饭","金额":-50,"类型":"支出"},
        {"事项":"交通","金额":-12,"类型":"支出"},
        {"事项":"购物","金额":-200,"类型":"支出"},
    ]
    total = 0
    print("=== 我的记账本 ===")
    for b in bills:
        total += b["金额"]
        print(b["事项"], b["类型"], b["金额"])
    print("总余额：", total)

my_money()
